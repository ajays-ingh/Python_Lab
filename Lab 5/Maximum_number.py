# Function to find the greater number
def maximum(a, b):
    if a > b:
        return a  # a is greater
    else:
        return b  # b is greater


num1 = 25
num2 = 40

result = maximum(num1, num2)

print("Greater number:", result)


# Output:
# Enter first number: 10
# Enter second number: 20
# The maximum number is: 20